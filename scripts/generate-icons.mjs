// Regenerates the PNG icons from public/icons/icon.svg.
// Needs `sharp`, which is not a project dependency:  npm i --no-save sharp && node scripts/generate-icons.mjs
import { readFile, writeFile } from 'node:fs/promises';
import sharp from 'sharp';

const svg = await readFile(new URL('../public/icons/icon.svg', import.meta.url));
const out = (name) => new URL(`../public/icons/${name}`, import.meta.url).pathname;

for (const size of [180, 192, 512]) {
  await sharp(svg, { density: 384 }).resize(size, size).png().toFile(out(`icon-${size}.png`));
}

// Maskable icon: the artwork must sit inside the central 80% "safe zone", on a full-bleed background.
const inner = await sharp(svg, { density: 384 }).resize(360, 360).png().toBuffer();
await sharp({ create: { width: 512, height: 512, channels: 4, background: '#0E5A55' } })
  .composite([{ input: inner, gravity: 'centre' }])
  .png()
  .toFile(out('icon-maskable-512.png'));

await writeFile(out('.generated'), 'Generated by scripts/generate-icons.mjs\n');
console.log('icons written');
